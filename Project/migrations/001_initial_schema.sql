CREATE TABLE teachers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  display_name TEXT NOT NULL,
  username TEXT NOT NULL UNIQUE,
  school_name TEXT NOT NULL DEFAULT '',
  salt TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE sessions (
  token_hash TEXT PRIMARY KEY,
  teacher_id INTEGER NOT NULL REFERENCES teachers(id) ON DELETE CASCADE,
  last_activity BIGINT NOT NULL
);

CREATE INDEX sessions_activity_idx ON sessions(last_activity);

CREATE TABLE students (
  id TEXT PRIMARY KEY,
  owner_id INTEGER NOT NULL REFERENCES teachers(id) ON DELETE CASCADE,
  school TEXT NOT NULL,
  student_name TEXT NOT NULL,
  age INTEGER NOT NULL,
  class_name TEXT NOT NULL,
  district TEXT NOT NULL,
  guardian_name TEXT NOT NULL,
  guardian_phone TEXT NOT NULL,
  guardian_email TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX students_owner_idx ON students(owner_id, created_at);

CREATE TABLE student_shares (
  student_id TEXT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  teacher_id INTEGER NOT NULL REFERENCES teachers(id) ON DELETE CASCADE,
  permission TEXT NOT NULL CHECK(permission IN ('view', 'edit')),
  granted_by INTEGER NOT NULL REFERENCES teachers(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY(student_id, teacher_id)
);

CREATE TABLE reports (
  id TEXT PRIMARY KEY,
  student_id TEXT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  created_by INTEGER NOT NULL REFERENCES teachers(id),
  student_name TEXT NOT NULL,
  class_name TEXT NOT NULL,
  school TEXT NOT NULL,
  term TEXT NOT NULL,
  academic_year TEXT NOT NULL,
  scores_json TEXT NOT NULL,
  total DOUBLE PRECISION NOT NULL,
  average DOUBLE PRECISION NOT NULL,
  teacher_name TEXT NOT NULL DEFAULT '',
  head_teacher_name TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX reports_student_idx ON reports(student_id, created_at);

CREATE TABLE school_logos (
  school_name TEXT PRIMARY KEY,
  school_name_key TEXT NOT NULL UNIQUE,
  mime_type TEXT NOT NULL CHECK(mime_type IN ('image/png', 'image/jpeg', 'image/webp')),
  image_data BYTEA NOT NULL,
  created_by INTEGER NOT NULL REFERENCES teachers(id),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE student_id_counters (
  year INTEGER PRIMARY KEY,
  last_value INTEGER NOT NULL CHECK(last_value > 0)
);
